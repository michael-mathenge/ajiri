"""Generate the reviewed contract without reading data or rewriting source files."""
import os
from pathlib import Path
import subprocess
import sys
import tempfile


def main():
    root = Path(__file__).resolve().parents[1]
    backend = root / 'ajiri-backend'
    env = {**os.environ, 'DEBUG': 'True', 'PYTHON_DOTENV_DISABLED': '1',
           'REAL_EMAIL_ENABLED': 'False', 'ALERT_EMAIL_ENABLED': 'False'}
    # see docs/CONCEPTS.md#api-version-contract
    with tempfile.TemporaryDirectory(prefix='ajiri-schema-') as folder:
        generated = Path(folder) / 'openapi.json'
        subprocess.run([sys.executable, str(backend / 'manage.py'), 'spectacular',
            '--settings=config.schema_settings', '--format', 'openapi-json',
            '--file', str(generated), '--validate', '--fail-on-warn'],
            cwd=backend, env=env, check=True)
        if generated.read_bytes() != (backend / 'config/openapi.json').read_bytes():
            raise SystemExit('OpenAPI drift: regenerate and review config/openapi.json.')
    print('OpenAPI validated; reviewed contract matches generated bytes.')


if __name__ == '__main__':
    main()
